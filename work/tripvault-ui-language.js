  function ui(value) {
    if (siteLanguage !== 'vi' || typeof value !== 'string') return value;
    const key = value.trim().replace(/\s+/g, ' ');
    if (!key) return value;
    let translated = vietnameseUI.get(key);
    if (translated === undefined) {
      for (const [pattern, replacement] of vietnamesePatterns) {
        if (!pattern.test(key)) continue;
        translated = key.replace(pattern, replacement);
        break;
      }
    }
    if (translated === undefined) return value;
    return value.match(/^\s*/)[0] + translated + value.match(/\s*$/)[0];
  }

  function localizeUI(root) {
    if (siteLanguage !== 'vi' || !root?.childNodes) return;
    for (const node of root.childNodes) {
      if (node.nodeType === 3) {
        node.nodeValue = ui(node.nodeValue);
      } else if (node.nodeType === 1 && !node.matches('[translate="no"], [data-site-language], [aria-hidden="true"], script, style')) {
        for (const attribute of ['aria-label', 'placeholder', 'title']) {
          if (node.hasAttribute(attribute)) node.setAttribute(attribute, ui(node.getAttribute(attribute)));
        }
        localizeUI(node);
      }
    }
  }

  function userText(value) {
    return siteLanguage === 'vi' ? '<span translate="no">' + safe(value) + '</span>' : safe(value);
  }

  function sheetText(value) {
    return typeof value === 'object' && value?.user !== undefined ? userText(value.user) : safe(value);
  }

  function siteLanguageSelect() {
    return '<span class="language-select"><select class="ui-language" data-site-language aria-label="' + ui('Language') + '">'
      + '<option value="en" lang="en"' + (siteLanguage === 'en' ? ' selected' : '') + '>English</option>'
      + '<option value="vi" lang="vi"' + (siteLanguage === 'vi' ? ' selected' : '') + '>Tiếng Việt</option></select></span>';
  }

  document.addEventListener('change', event => {
    const field = event.target;
    if (!field?.matches?.('[data-site-language]') || !['en', 'vi'].includes(field.value)) return;
    siteLanguage = field.value;
    try { localStorage.setItem(SITE_LANGUAGE_KEY, JSON.stringify(siteLanguage)); } catch {}
    render();
    app.querySelector?.('[data-site-language]')?.focus();
  });
