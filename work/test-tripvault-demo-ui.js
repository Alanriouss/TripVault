import assert from 'node:assert/strict';

export async function testDemoUi({ launch }) {
  const demoKey = 'tripvault-judge-demo-v1';
  const demo = await launch({ url: 'http://127.0.0.1:8788/?demo=1', language: 'en' });
  demo.click('judge-demo-sample');
  assert.match(demo.page.innerHTML, /class="panel fund-summary"/);
  assert.match(demo.page.innerHTML, /class="panel trip-progress"/);
  assert.match(demo.page.innerHTML, /data-view="split"/);
  assert.doesNotMatch(demo.page.innerHTML, /class="metrics"|class="overview-grid"|fuji-connect/);
  demo.view('people');
  assert.match(demo.page.innerHTML, /Members<\/h2>/);
  assert.match(demo.page.innerHTML, /Organizer/);
  assert.doesNotMatch(demo.page.innerHTML, /traveler-details/);
  demo.view('wallet');
  assert.match(demo.page.innerHTML, /Wallet and trip fund/);
  assert.match(demo.page.innerHTML, /Your balance in the trip fund/);
  assert.doesNotMatch(demo.page.innerHTML, /Fuji testnet and local demo|fuji-connect/);
  demo.fund(1);
  demo.view('overview');
  assert.match(demo.page.innerHTML, /11\.00 USDC/);
  demo.view('split');
  assert.match(demo.page.innerHTML, /room-final-split/);
  assert.match(demo.page.innerHTML, /split-payment/);
  assert.match(demo.page.innerHTML, /Nothing to split yet/);
  demo.bill(100000);
  demo.click('bill-detail', { id: '1' });
  assert.match(demo.sheet.innerHTML, /People sharing this bill/);
  assert.match(demo.sheet.innerHTML, /50\.0%/);
  assert.doesNotMatch(demo.sheet.innerHTML, /Sign in again|data-room-sign-in/);
  demo.approveBill(1);
  demo.member('m1');
  demo.approveBill(1);
  demo.member('m0');
  await demo.prepare();
  assert.match(demo.page.innerHTML, /split-amount/);
  assert.match(demo.page.innerHTML, /Who pays whom/);
  demo.approvals();
  demo.click('settle');
  assert.equal(JSON.parse(demo.storage.get(demoKey)).trips[0].settled, true);
  demo.view('wallet');
  assert.match(demo.page.innerHTML, /data-act="claim"/);
  const restored = await launch({ url: 'http://127.0.0.1:8788/?demo=1', storage: demo.storage });
  assert.match(restored.page.innerHTML, /Wallet and trip fund/);
  assert.equal(demo.requests(), 0);
  assert.equal(restored.requests(), 0);
  assert.equal(demo.storage.has('tripvault-timelocked-external-v8'), false);
  console.log('PASS: Demo reuses the shared layouts, persists funding, and settles without wallet or network requests');
}
