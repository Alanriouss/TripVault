import assert from 'node:assert/strict';

export async function testDemoUi({ launch }) {
  const demoKey = 'tripvault-judge-demo-v1';
  const demo = await launch({ url: 'http://127.0.0.1:8788/?demo=1', language: 'en' });
  demo.click('judge-demo-sample');
  assert.match(demo.page.innerHTML, /class="panel fund-summary"/);
  assert.match(demo.page.innerHTML, /class="panel trip-progress"/);
  assert.match(demo.page.innerHTML, /data-view="split"/);
  assert.doesNotMatch(demo.page.innerHTML, /class="metrics"|class="overview-grid"|fuji-connect/);
  demo.view('people');
  assert.match(demo.page.innerHTML, /Members<\/h2>/);
  assert.match(demo.page.innerHTML, /Organizer/);
  assert.doesNotMatch(demo.page.innerHTML, /traveler-details/);
  demo.view('wallet');
  assert.match(demo.page.innerHTML, /Wallet and trip fund/);
  assert.match(demo.page.innerHTML, /Your balance in the trip fund/);
  assert.doesNotMatch(demo.page.innerHTML, /Fuji testnet and local demo|fuji-connect/);
  demo.fund(1);
  demo.view('overview');
  assert.match(demo.page.innerHTML, /11\.00 USDC/);
  demo.view('split');
  assert.match(demo.page.innerHTML, /room-final-split/);
  assert.match(demo.page.innerHTML, /split-payment/);
  assert.match(demo.page.innerHTML, /Nothing to split yet/);
  demo.bill(100000);
  demo.click('bill-detail', { id: '1' });
  assert.match(demo.sheet.innerHTML, /People sharing this bill/);
  assert.match(demo.sheet.innerHTML, /50\.0%/);
  assert.doesNotMatch(demo.sheet.innerHTML, /Sign in again|data-room-sign-in/);
  demo.approveBill(1);
  demo.member('m1');
  demo.approveBill(1);
  demo.member('m0');
  await demo.prepare();
  assert.match(demo.page.innerHTML, /split-amount/);
  assert.match(demo.page.innerHTML, /Who pays whom/);
  demo.approvals();
  demo.click('settle');
  assert.equal(JSON.parse(demo.storage.get(demoKey)).trips[0].settled, true);
  demo.view('wallet');
  assert.match(demo.page.innerHTML, /data-act="claim"/);
  const restored = await launch({ url: 'http://127.0.0.1:8788/?demo=1', storage: demo.storage });
  assert.match(restored.page.innerHTML, /Wallet and trip fund/);
  assert.equal(demo.requests(), 0);
  assert.equal(restored.requests(), 0);
  assert.equal(demo.storage.has('tripvault-timelocked-external-v8'), false);
  await testDemoBillReviews({ launch });
  console.log('PASS: Demo reuses the shared layouts, persists funding, and settles without wallet or network requests');
}

async function testDemoBillReviews({ launch }) {
  const key = 'tripvault-judge-demo-v1';
  const demo = await launch({ url: 'http://127.0.0.1:8788/?demo=1', language: 'en' });
  const trip = () => JSON.parse(demo.storage.get(key)).trips[0];
  demo.click('judge-demo-sample');
  demo.bill(100000, 'm1');
  demo.click('bill-detail', { id: '1' });
  assert.match(demo.sheet.innerHTML, /data-act="bill-feedback"/);
  assert.match(demo.sheet.innerHTML, /data-act="bill-cancel-yes"/);
  demo.member('m1');
  demo.click('bill-feedback', { id: '1' });
  assert.match(demo.sheet.innerHTML, /bill-feedback-form/);
  assert.doesNotMatch(demo.sheet.innerHTML, /Sign in again/);
  assert.ok(demo.submit('bill-feedback-form', { id: '1', comment: ' ' }));
  demo.submit('bill-feedback-form', { id: '1', comment: 'Please reduce this to 80000' });
  assert.equal(trip().bills[0].status, 'disputed');
  demo.member('m0');
  demo.click('room-notifications');
  assert.match(demo.sheet.innerHTML, /Bill change requested/);
  assert.match(demo.sheet.innerHTML, /Please reduce this to 80000/);
  demo.click('bill-detail', { id: '1' });
  const suggestion = trip().bills[0].feedback[0];
  assert.match(demo.sheet.innerHTML, /data-act="bill-feedback-vote"/);
  demo.click('bill-feedback-vote', { id: '1', author: 'm1', suggestion: suggestion.id, agree: 'false' });
  assert.equal(trip().bills[0].feedback[0].responses[0].agree, false);
  demo.member('m1');
  demo.click('room-notifications');
  assert.match(demo.sheet.innerHTML, /Someone disagreed with the suggestion/);
  const responseNotice = demo.sheet.innerHTML.match(/data-notification-id="([^"]*bill-event[^"]*)"/)[1];
  demo.click('open-room-notification', { id: responseNotice });
  assert.equal(JSON.parse(demo.storage.get(key)).actor, 'm1', 'opening a notification preserves the selected demo member');
  assert.match(demo.sheet.innerHTML, /Someone|Please reduce this to 80000/);
  demo.member('m0');
  demo.click('bill-feedback-vote', { id: '1', author: 'm1', suggestion: suggestion.id, agree: 'true' });
  assert.equal(trip().bills[0].feedback[0].responses.length, 1);
  assert.equal(trip().bills[0].feedback[0].responses[0].agree, true);
  demo.click('bill-edit', { id: '1' });
  assert.match(demo.sheet.innerHTML, /name="editing" value="1"/);
  demo.submit('bill-form', { editing: '1', label: 'Corrected bill', amount: '80000', payer: 'm1', participant: ['m0', 'm1'] });
  assert.equal(trip().bills.length, 1);
  assert.equal(trip().bills[0].amount, 80000);
  assert.equal(trip().bills[0].status, 'pending');
  assert.equal(trip().bills[0].history[0].feedback[0].comment, 'Please reduce this to 80000');
  demo.member('m1');
  demo.click('bill-cancel-yes', { id: '1' });
  assert.match(demo.sheet.innerHTML, /bill-cancellation-form/);
  demo.submit('bill-cancellation-form', { id: '1', reason: 'Duplicate expense' });
  assert.equal(trip().bills[0].status, 'cancellation');
  demo.member('m0');
  demo.click('room-notifications');
  assert.match(demo.sheet.innerHTML, /Bill removal requested/);
  assert.match(demo.sheet.innerHTML, /Duplicate expense/);
  demo.click('bill-cancel-no', { id: '1' });
  assert.equal(trip().bills[0].status, 'pending');
  demo.member('m1');
  demo.click('bill-cancel-yes', { id: '1' });
  demo.submit('bill-cancellation-form', { id: '1', reason: 'Handle separately' });
  demo.approveBill(1);
  assert.equal(trip().bills[0].status, 'cancellation', 'approval cannot bypass a removal request');
  demo.member('m0');
  demo.click('bill-cancel-yes', { id: '1' });
  assert.equal(trip().bills[0].status, 'rejected');
  assert.equal(trip().bills[0].cancellation.reason, 'Handle separately');
  await demo.prepare();
  assert.ok(trip().reviewQuote, 'rejected bills do not block final payments');
  const reloaded = await launch({ url: 'http://127.0.0.1:8788/?demo=1', storage: demo.storage });
  reloaded.click('bill-detail', { id: '1' });
  assert.match(reloaded.sheet.innerHTML, /Handle separately/);
  assert.doesNotMatch(reloaded.sheet.innerHTML, /data-act="bill-feedback"|data-act="bill-cancel-yes"/);
  assert.equal(demo.requests(), 0);
  assert.equal(reloaded.requests(), 0);
  demo.click('judge-demo-sample');
  const legacy = JSON.parse(demo.storage.get(key));
  legacy.trips[0].members.push({ id: 'm2', name: 'Chi' });
  legacy.trips[0].depositUnits.m2 = 5000000;
  const legacyDemo = await launch({ url: 'http://127.0.0.1:8788/',
    storage: new Map([['tripvault-timelocked-external-v8', JSON.stringify(legacy)], [key, JSON.stringify(legacy)]]) });
  const legacyTrip = () => [key, 'tripvault-timelocked-external-v8']
    .map(storageKey => JSON.parse(legacyDemo.storage.get(storageKey)).trips[0]).find(item => item.bills.length);
  assert.match(legacyDemo.page.innerHTML, /trip-progress/);
  legacyDemo.bill(90000, 'm1', ['m1', 'm2']);
  legacyDemo.click('bill-detail', { id: '1' });
  assert.match(legacyDemo.sheet.innerHTML, /bill-cancel-yes/);
  assert.doesNotMatch(legacyDemo.sheet.innerHTML, /data-act="approve-bill"/);
  legacyDemo.member('m1');
  legacyDemo.click('bill-cancel-yes', { id: '1' });
  legacyDemo.submit('bill-cancellation-form', { id: '1', reason: 'All involved must agree' });
  legacyDemo.member('m2');
  legacyDemo.click('bill-cancel-yes', { id: '1' });
  assert.equal(legacyTrip().bills[0].status, 'cancellation', 'the creator must also agree even when not sharing the bill');
  legacyDemo.member('m0');
  legacyDemo.click('bill-cancel-yes', { id: '1' });
  assert.equal(legacyTrip().bills[0].status, 'rejected');
  console.log('PASS: Demo suggestions, responses, recipient notifications, editing, and unanimous bill cancellation persist locally');
}
